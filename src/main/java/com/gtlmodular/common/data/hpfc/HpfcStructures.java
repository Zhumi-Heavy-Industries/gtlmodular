    static BlockPattern build(MultiblockMachineDefinition definition) {
        FactoryBlockPattern pattern = FactoryBlockPattern.start();
        for (String[] slice : SLICES) {
            pattern.aisle(slice);
        }

        // A / H：超维度机械方块（纯外壳，不放仓）。
        TraceabilityPredicate plainCasing = blocksOf("gtlcore", "dimensionally_transcendent_casing");

        // B：超维度机械方块 + 并行仓（上限 1）+ 常规 IO / 能源 / 激光仓 + 线程仓（上限 1）
        //    —— 对齐 GTO 的 `blocks(DIMENSIONALLY_TRANSCENDENT_CASING)
        //       .or(abilities(PARALLEL_HATCH).setMaxGlobalLimited(1))
        //       .or(GTOPredicates.autoThreadLaserAbilities(definition.getRecipeTypes()))`。
        //    GTO 的 autoThreadLaserAbilities = autoLaserAbilities + THREAD_HATCH(限1)
        //    + OVERCLOCK_HATCH(限1) + ACCELERATE_HATCH(限1)；本包没有后两种能力（gtlcore /
        //    gtladditions 都没有对应方块），照旧跳过。**线程仓 2026-11-02 已接**：
        //    本模组 `gtlmodular:thread_hatch_<tier>`（UV=4 … MAX=256）挂在与 GTO 同名的自定义
        //    PartAbility[thread_hatch] 下，一条谓词即可收全部 7 档；控制器侧由
        //    HyperdimensionalPlasmaFusionCoreMachine#baseThreads() 求和驱动独立线程引擎。
        TraceabilityPredicate hatchableCasing = blocksOf("gtlcore", "dimensionally_transcendent_casing")
                .or(ability(PartAbility.PARALLEL_HATCH).setMaxGlobalLimited(1).setPreviewCount(1))
                .or(ability(PartAbility.IMPORT_ITEMS).setPreviewCount(1))
                .or(ability(PartAbility.EXPORT_ITEMS).setPreviewCount(1))
                .or(ability(PartAbility.IMPORT_FLUIDS).setPreviewCount(1))
                .or(ability(PartAbility.EXPORT_FLUIDS).setPreviewCount(1))
                .or(ability(PartAbility.INPUT_ENERGY).setMaxGlobalLimited(2))
                .or(ability(PartAbility.INPUT_LASER).setMaxGlobalLimited(1))
                // —— GTO 线程仓（setMaxGlobalLimited(1)，与 GTO 原谓词同口径）；
                //    GTO 这条没有 previewCount ⇒ 预览格不占位，只在点开候选时出现。
                .or(ability(ThreadHatchMachines.THREAD_HATCH).setMaxGlobalLimited(1))
                .or(com.gtlmodular.common.data.fuel.OverclockHatches.predicate())
                .or(com.gtlmodular.common.data.fuel.AccelerateHatches.predicate());

        return pattern
                .where('A', plainCasing)
                .where('B', hatchableCasing)
                .where('C', blocksOf("gtceu", "neutronium_frame"))
                .where('D', blocksOf("gtlcore", "sps_casing"))
                .where('E', absCasings())
                .where('F', Predicates.blocks(HpfcBlocks.STRONTIUM_CARBONATE_CERAMIC_RAY_ABSORBING_CUBE.get()))
                .where('G', blocksOf("gtceu", "fusion_glass"))
                .where('H', blocksOf("gtlcore", "dimensionally_transcendent_casing"))
                .where('I', blocksOf("gtceu", "high_power_casing"))
                .where('J', blocksOf("kubejs", "molecular_coil"))
                .where('K', blocksOf("gtceu", "naquadria_frame"))
                .where('L', blocksOf("gtlcore", "hyper_core"))
                .where('M', blocksOf("kubejs", "dimensional_bridge_casing"))
                .where('N', Predicates.blocks(HpfcBlocks.ABS_ORANGE_CASING.get()))
                .where('O', blocksOf("kubejs", "high_strength_concrete"))
                .where('P', Predicates.heatingCoils())
                .where('Q', Predicates.blocks(HpfcBlocks.COBALT_OXIDE_CERAMIC_STRONG_THERMALLY_CONDUCTIVE_BLOCK.get()))
                .where('R', blocksOf("gtlcore", "rhenium_reinforced_energy_glass"))
                .where('S', blocksOf("kubejs", "hollow_casing"))
                .where('T', blocksOf("gtlcore", "dimension_injection_casing"))
                .where('U', Predicates.controller(Predicates.blocks(definition.get())))
                .where(' ', Predicates.any())
                .build();
    }

    /** E 位：GTO 的 {@code absBlocks()} = 16 色 ABS 机壳任选（白 + 15 色染料化学浴变体）。 */
    private static TraceabilityPredicate absCasings() {
        return Predicates.blocks(HpfcBlocks.ABS_CASINGS.stream().map(BlockEntry::get)
                .toArray(Block[]::new));
    }

